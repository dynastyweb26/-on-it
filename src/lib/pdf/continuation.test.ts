// Tests for the continuation-page geometry (page 2+ of a multi-page PDF).
// The math runs against a fake DOM chain (no jsdom): contentInset walks the
// same parent chain the browser gives it. A second block drives the REAL jsPDF
// to prove a single-page document still adds no pages and that attachment pages
// keep landing after the document page, painting the document background.
import test from 'node:test';
import assert from 'node:assert/strict';
import { jsPDF } from 'jspdf';
import { appendAttachmentPages, attachmentPageCount, hexToRgb, type PdfAttachment } from './attachment-pages';
import { BRANDING_TEXT, contentInset, continuationStyle, footerTextColor, pinsBrandingLine, PAGE_W, type BoxLike, type PageInset } from './continuation';
import { mixColors } from '@/lib/colors';

/** A fake DOM node: its own padding+border box, and its parent. */
type FakeBox = BoxLike & { box: PageInset };
const box = (b: Partial<PageInset> = {}, parent: FakeBox | null = null): FakeBox => ({
  parentElement: parent,
  box: { top: 0, right: 0, bottom: 0, left: 0, ...b },
});
const boxOf = (n: BoxLike) => (n as FakeBox).box;

test('contentInset: sums padding + border from the table up to the page root', () => {
  // Classic: the page root (padding 56) is the table's only padded ancestor.
  const classicRoot = box({ top: 56, right: 56, bottom: 56, left: 56 });
  const classicTable = box({}, classicRoot);
  assert.deepEqual(contentInset(classicTable, classicRoot, boxOf), { top: 56, right: 56, bottom: 56, left: 56 });

  // Industrial: the root has no padding; the body wrapper supplies it.
  const indRoot = box();
  const indBody = box({ top: 36, right: 56, bottom: 36, left: 56 }, indRoot);
  const indTable = box({}, indBody);
  assert.deepEqual(contentInset(indTable, indRoot, boxOf), { top: 36, right: 56, bottom: 36, left: 56 });

  // Friendly: the table sits in a padded, bordered card inside the padded root,
  // so the insets ADD (48 + 12 padding + 1.5 border = 61.5).
  const friendlyRoot = box({ top: 48, right: 48, bottom: 48, left: 48 });
  const card = box({ top: 13.5, right: 13.5, bottom: 13.5, left: 13.5 }, friendlyRoot);
  const friendlyTable = box({}, card);
  assert.deepEqual(contentInset(friendlyTable, friendlyRoot, boxOf), { top: 61.5, right: 61.5, bottom: 61.5, left: 61.5 });

  // Ledger: padded root, unpadded flex columns between it and the table.
  const ledgerRoot = box({ top: 64, right: 64, bottom: 64, left: 64 });
  const flex = box({}, ledgerRoot);
  const column = box({}, flex);
  const ledgerTable = box({}, column);
  assert.deepEqual(contentInset(ledgerTable, ledgerRoot, boxOf), { top: 64, right: 64, bottom: 64, left: 64 });
});

test('contentInset: no table → the page root box alone', () => {
  const root = box({ top: 48, right: 48, bottom: 48, left: 48 });
  assert.deepEqual(contentInset(null, root, boxOf), { top: 48, right: 48, bottom: 48, left: 48 });
});

test('continuationStyle: keeps page 1 background and page 1 table width', () => {
  // Friendly: 794 − 2×61.5 = 671px, exactly page 1's card-inset table.
  const friendly = continuationStyle({ background: '#0f1416', inset: { top: 61.5, right: 61.5, bottom: 61.5, left: 61.5 } });
  assert.equal(friendly.background, '#0f1416');            // page 2 paints page 1's canvas
  assert.equal(friendly.padding, '61.5px 61.5px 61.5px 61.5px');
  assert.equal(friendly.tableWidth, 671);

  // Classic: 794 − 2×56 = 682px, exactly page 1's table.
  assert.equal(continuationStyle({ background: '#fff', inset: { top: 56, right: 56, bottom: 56, left: 56 } }).tableWidth, 682);
  // Ledger: the full content width (794 − 128 = 666), NOT page 1's rail-narrowed table.
  assert.equal(continuationStyle({ background: '#fff', inset: { top: 64, right: 64, bottom: 64, left: 64 } }).tableWidth, 666);

  // The old hardcoded 48/56 inset did NOT match page 1 for Friendly (698 vs 671).
  const old = continuationStyle({ background: '#fff', inset: { top: 48, right: 56, bottom: 48, left: 56 } });
  assert.equal(old.tableWidth, PAGE_W - 112);
  assert.notEqual(old.tableWidth, friendly.tableWidth);
});

test('footerTextColor: page 1 "Generated by On It" grey, in any CSS form', () => {
  // Exactly the value buildTheme derives for the templates' muted token.
  assert.equal(footerTextColor('#ffffff', '#111111'), mixColors('#ffffff', '#111111', 0.62));
  assert.equal(footerTextColor('#0f1416', '#f5f5f5'), mixColors('#0f1416', '#f5f5f5', 0.62));
  // getComputedStyle hands back rgb(); the same colour must resolve the same.
  assert.equal(footerTextColor('rgb(255, 255, 255)', 'rgb(17, 17, 17)'), footerTextColor('#ffffff', '#111111'));
  // On a dark template the line is a light grey, never the page's own text.
  assert.notEqual(footerTextColor('#0f1416', '#f5f5f5'), '#f5f5f5');
});

test('pinsBrandingLine: invoices reprint the line, the books summaries do not', () => {
  // The invoice/quote templates' Branding node: absolute, non-block, bottom 14.
  assert.equal(pinsBrandingLine({ absolute: true, block: false, bottom: 14, text: 'Generated by On It' }), true);
  assert.equal(pinsBrandingLine({ absolute: true, block: false, bottom: 14, text: `  ${BRANDING_TEXT}\n` }), true);
  // Totals/income summaries: a pinned footer, but at bottom 44.
  assert.equal(pinsBrandingLine({ absolute: true, block: false, bottom: 44, text: 'Generated by On It' }), false);
  // Itemized/income footers are last-page data-pdf-blocks (bottom 44 there too).
  assert.equal(pinsBrandingLine({ absolute: true, block: true, bottom: 14, text: 'Generated by On It' }), false);
  // The page indicator and the invoice closing line are not the marketing line.
  assert.equal(pinsBrandingLine({ absolute: true, block: false, bottom: 14, text: 'Page 1 of 2' }), false);
  assert.equal(pinsBrandingLine({ absolute: false, block: false, bottom: 14, text: 'Generated by On It' }), false);
});

// Minimal 1×1 PNG; jsPDF parses PNG itself, so no canvas is needed in Node.
const PIXEL = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==';
const img = (): PdfAttachment => ({ dataUrl: PIXEL, width: 1, height: 1 });

/** jsPDF round-trips a colour through its colour space, so ±2 per channel. */
const near = (a: [number, number, number], b: [number, number, number]) => a.every((v, i) => Math.abs(v - b[i]) <= 2);

test('real jsPDF: a single-page document stays one page with no attachments', () => {
  const pdf = new jsPDF({ unit: 'px', format: [794, 1123], compress: true });
  pdf.text('INVOICE', 40, 40);
  assert.equal(pdf.getNumberOfPages(), 1);
  assert.equal(appendAttachmentPages(pdf, [], '#ffffff'), 0);
  assert.equal(pdf.getNumberOfPages(), 1);
});

test('real jsPDF: attachment pages still follow the document page, on its background', () => {
  for (const n of [1, 2, 3, 6]) {
    const pdf = new jsPDF({ unit: 'px', format: [794, 1123], compress: true });
    pdf.text('INVOICE + HOW TO PAY', 40, 40);           // the body + payment block page
    const added = appendAttachmentPages(pdf, Array.from({ length: n }, img), '#101418');
    assert.equal(added, attachmentPageCount(n), `n=${n} extra pages`);
    assert.equal(pdf.getNumberOfPages(), 1 + attachmentPageCount(n), `n=${n} total pages`);
    assert.ok(near(hexToRgb(pdf.getFillColor()), hexToRgb('#101418')), `n=${n} paints the document canvas`);
  }
});
